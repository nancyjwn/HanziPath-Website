/**
 * Returns a list of candidate Chinese characters or compound phrases
 * for a given search query (Latin / Pinyin).
 */
export function getPinyinCandidates(rawInput) {
  if (!rawInput || typeof rawInput !== 'string') return []
  const clean = rawInput.trim().toLowerCase().replace(/[^a-z]/g, '')
  if (!clean) return []

  const candidates = []

  // 1. Direct compound phrase match (e.g. "nihao", "xiexie", "water")
  if (COMPOUND_IME_DICT[clean]) {
    COMPOUND_IME_DICT[clean].forEach((word) => {
      if (!candidates.includes(word)) candidates.push(word)
    })
  }

  // 2. Direct syllable match (e.g. "ni" -> ['你', '呢', '拟', '泥', '尼'])
  if (PINYIN_SYLLABLE_DICT[clean]) {
    PINYIN_SYLLABLE_DICT[clean].forEach((char) => {
      if (!candidates.includes(char)) candidates.push(char)
    })
  }

  // 3. Prefix matching on compound dictionary (e.g. typing "xiex" -> suggest "谢谢")
  if (clean.length >= 2) {
    Object.keys(COMPOUND_IME_DICT).forEach((key) => {
      if (key.startsWith(clean) && key !== clean) {
        COMPOUND_IME_DICT[key].forEach((word) => {
          if (!candidates.includes(word)) candidates.push(word)
        })
      }
    })
  }

  // 4. Prefix matching on syllable dictionary (e.g. typing "zhon" -> suggest "中", "重")
  if (clean.length >= 2) {
    Object.keys(PINYIN_SYLLABLE_DICT).forEach((key) => {
      if (key.startsWith(clean) && key !== clean) {
        PINYIN_SYLLABLE_DICT[key].slice(0, 3).forEach((char) => {
          if (!candidates.includes(char)) candidates.push(char)
        })
      }
    })
  }

  return candidates.slice(0, 8)
}

